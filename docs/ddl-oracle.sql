-- Tá Normal? - tabelas usadas pela API (Oracle 19c / Oracle da FIAP)
-- A API cria essas tabelas sozinha (spring.jpa.hibernate.ddl-auto=update).
-- Este script serve para o Database Design usar o mesmo modelo.

CREATE TABLE TN_USUARIO (
    ID_USUARIO   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO   VARCHAR2(100) NOT NULL,
    DS_EMAIL     VARCHAR2(120) NOT NULL,
    DT_CADASTRO  TIMESTAMP     NOT NULL,
    CONSTRAINT PK_TN_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UN_TN_USUARIO_EMAIL UNIQUE (DS_EMAIL)
);

CREATE TABLE TN_LINHA (
    ID_LINHA              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NR_LINHA              NUMBER(10)   NOT NULL,
    NM_LINHA              VARCHAR2(40) NOT NULL,
    DS_OPERADORA          VARCHAR2(20) NOT NULL,
    DS_STATUS_OFICIAL     VARCHAR2(30) NOT NULL,
    DT_ATUALIZACAO_STATUS TIMESTAMP,
    CONSTRAINT PK_TN_LINHA PRIMARY KEY (ID_LINHA),
    CONSTRAINT UN_TN_LINHA_NUMERO UNIQUE (NR_LINHA),
    CONSTRAINT CK_TN_LINHA_OPERADORA CHECK (DS_OPERADORA IN ('METRO','CPTM','VIAQUATRO','VIAMOBILIDADE')),
    CONSTRAINT CK_TN_LINHA_STATUS CHECK (DS_STATUS_OFICIAL IN ('NORMAL','VELOCIDADE_REDUZIDA','OPERACAO_PARCIAL','PARALISADA'))
);

CREATE TABLE TN_ESTACAO (
    ID_ESTACAO  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_ESTACAO  VARCHAR2(80) NOT NULL,
    ID_LINHA    NUMBER(19)   NOT NULL,
    CONSTRAINT PK_TN_ESTACAO PRIMARY KEY (ID_ESTACAO),
    CONSTRAINT FK_TN_ESTACAO_LINHA FOREIGN KEY (ID_LINHA) REFERENCES TN_LINHA (ID_LINHA)
);

CREATE TABLE TN_TRAJETO (
    ID_TRAJETO          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO          NUMBER(19)   NOT NULL,
    NM_TRAJETO          VARCHAR2(60) NOT NULL,
    ID_ESTACAO_ORIGEM   NUMBER(19)   NOT NULL,
    ID_ESTACAO_DESTINO  NUMBER(19)   NOT NULL,
    HR_SAIDA            DATE         NOT NULL,
    NR_TEMPO_NORMAL_MIN NUMBER(10)   NOT NULL,
    CONSTRAINT PK_TN_TRAJETO PRIMARY KEY (ID_TRAJETO),
    CONSTRAINT FK_TN_TRAJETO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TN_USUARIO (ID_USUARIO),
    CONSTRAINT FK_TN_TRAJETO_ORIGEM FOREIGN KEY (ID_ESTACAO_ORIGEM) REFERENCES TN_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_TN_TRAJETO_DESTINO FOREIGN KEY (ID_ESTACAO_DESTINO) REFERENCES TN_ESTACAO (ID_ESTACAO)
);

-- Linhas usadas em cada trajeto, na ordem da viagem (associativa N:N)
CREATE TABLE TN_TRAJETO_LINHA (
    ID_TRAJETO  NUMBER(19) NOT NULL,
    NR_ORDEM    NUMBER(10) NOT NULL,
    ID_LINHA    NUMBER(19) NOT NULL,
    CONSTRAINT PK_TN_TRAJETO_LINHA PRIMARY KEY (ID_TRAJETO, NR_ORDEM),
    CONSTRAINT FK_TN_TL_TRAJETO FOREIGN KEY (ID_TRAJETO) REFERENCES TN_TRAJETO (ID_TRAJETO),
    CONSTRAINT FK_TN_TL_LINHA FOREIGN KEY (ID_LINHA) REFERENCES TN_LINHA (ID_LINHA)
);

CREATE TABLE TN_RELATO (
    ID_RELATO        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO       NUMBER(19)   NOT NULL,
    ID_LINHA         NUMBER(19)   NOT NULL,
    ID_ESTACAO       NUMBER(19),
    DS_TIPO          VARCHAR2(20) NOT NULL,
    DS_COMENTARIO    VARCHAR2(200),
    DT_RELATO        TIMESTAMP    NOT NULL,
    NR_CONFIRMACOES  NUMBER(10)   NOT NULL,
    CONSTRAINT PK_TN_RELATO PRIMARY KEY (ID_RELATO),
    CONSTRAINT FK_TN_RELATO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TN_USUARIO (ID_USUARIO),
    CONSTRAINT FK_TN_RELATO_LINHA FOREIGN KEY (ID_LINHA) REFERENCES TN_LINHA (ID_LINHA),
    CONSTRAINT FK_TN_RELATO_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES TN_ESTACAO (ID_ESTACAO),
    CONSTRAINT CK_TN_RELATO_TIPO CHECK (DS_TIPO IN ('PARADO','LENTO','LOTADO'))
);

CREATE TABLE TN_OCORRENCIA (
    ID_OCORRENCIA  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_LINHA       NUMBER(19)   NOT NULL,
    DS_STATUS      VARCHAR2(30) NOT NULL,
    DS_FONTE       VARCHAR2(20) NOT NULL,
    DS_OCORRENCIA  VARCHAR2(300),
    ST_CHUVA       NUMBER(1)    NOT NULL,
    DT_INICIO      TIMESTAMP    NOT NULL,
    DT_FIM         TIMESTAMP,
    CONSTRAINT PK_TN_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT FK_TN_OCORRENCIA_LINHA FOREIGN KEY (ID_LINHA) REFERENCES TN_LINHA (ID_LINHA),
    CONSTRAINT CK_TN_OCORRENCIA_FONTE CHECK (DS_FONTE IN ('OFICIAL','PASSAGEIROS')),
    CONSTRAINT CK_TN_OCORRENCIA_CHUVA CHECK (ST_CHUVA IN (0,1))
);
